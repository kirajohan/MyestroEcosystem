"""AI Memory System models — chat sessions and context management."""

from datetime import datetime, timedelta
from sqlalchemy import (
    Column, BigInteger, String, Boolean, Text, Integer, DateTime, 
    ForeignKey, Index, UUID
)
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func
from app.database import Base
import uuid


class AIMemorySession(Base):
    """User's AI chat session with context and history tracking."""
    
    __tablename__ = "ai_memory_sessions"

    id = Column(BigInteger, primary_key=True, autoincrement=True)
    user_id = Column(BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    session_id = Column(
        PG_UUID(as_uuid=True), 
        unique=True, 
        default=uuid.uuid4, 
        nullable=False
    )
    
    # Session metadata
    title = Column(String(255), nullable=True)  # e.g. "English Speaking Practice"
    language = Column(String(10), nullable=False, default="uz")
    cefr_level = Column(String(10), nullable=True)  # User's current level
    
    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    last_activity_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    expires_at = Column(DateTime(timezone=True), nullable=False)  # Auto-delete after 7 days
    
    # Memory management
    message_count = Column(Integer, nullable=False, default=0)
    is_active = Column(Boolean, nullable=False, default=True)
    
    # Context summary (generated by AI when messages > 15)
    context_summary = Column(Text, nullable=True)
    summary_generated_at = Column(DateTime(timezone=True), nullable=True)
    
    # Relationships
    messages = relationship(
        "Message",
        foreign_keys="Message.session_id",
        back_populates="memory_session",
        cascade="all, delete-orphan"
    )
    
    __table_args__ = (
        Index("idx_ai_memory_sessions_user_id", "user_id"),
        Index("idx_ai_memory_sessions_expires_at", "expires_at"),
        Index("idx_ai_memory_sessions_last_activity", "last_activity_at", postgresql_using="DESC"),
        # Ensure only one active session per user
        Index("idx_ai_memory_sessions_user_active", "user_id", "is_active", unique=True),
    )
    
    def is_expired(self) -> bool:
        """Check if session has expired."""
        return datetime.utcnow() >= self.expires_at
    
    @staticmethod
    def create_new(user_id: int, language: str = "uz", cefr_level: str = None) -> "AIMemorySession":
        """Factory method to create new session with 7-day expiry."""
        return AIMemorySession(
            user_id=user_id,
            language=language,
            cefr_level=cefr_level,
            expires_at=datetime.utcnow() + timedelta(days=7),
            title=f"Chat Session - {datetime.now().strftime('%Y-%m-%d %H:%M')}"
        )